    /// Live: needs `dsh` and a NexusAI server (`NEXUS_TEST_NEXUSAI_URL`).
    /// `NEXUS_TEST_NEXUSAI_URL=http://…:8081/v1 cargo test -p nexus-providers dsh -- --ignored`
    #[test]
    #[ignore]
    fn live_turn_on_nexusai() {
        let url = std::env::var("NEXUS_TEST_NEXUSAI_URL").expect("set NEXUS_TEST_NEXUSAI_URL");
        let p = DshProvider { nexusai_url: Some(url) };
        let c = p.verify();
        assert!(c.is_connected(), "{}", c.label());
        let dir = tempfile::tempdir().unwrap();
        std::fs::write(dir.path().join("note.txt"), "hello from nexus\n").unwrap();
        let mut r = req(Mode::Ask, ToolPolicy::READ_ONLY);
        r.workspace = dir.path().to_path_buf();
        r.prompt = "Read note.txt with a tool and tell me its contents.".into();
        let (tx, rx) = mpsc::channel();
        let _h = p.start(r, EventSink::new(tx, Arc::new(|| {}))).unwrap();
        let mut text = String::new();
        let mut tools = 0;
        loop {
            match rx.recv_timeout(Duration::from_secs(900)).expect("turn timed out") {
                Event::Text(t) => text.push_str(&t),
                Event::Tool { .. } => tools += 1,
                Event::Error(e) => panic!("{e}"),
                Event::Done { .. } => break,
                _ => {}
            }
        }
        assert!(tools >= 1, "no tool call");
        assert!(text.contains("hello from nexus"), "{text}");
    }
